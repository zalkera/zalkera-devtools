/**
 * **계정에 딸린 상태 — 로그아웃이 남기면 안 되는 것.**
 *
 * ■ 왜 목록인가
 *   로그아웃은 자리를 여럿 지운다(토큰·발급 열쇠·`.env.local` 의 키 줄·고른 사이트). 지우는
 *   자리를 코드 흐름에만 두면 **하나가 조용히 빠진다** — 실제로 「고른 사이트」가 빠져 있었고,
 *   A 로 로그아웃하고 B 로 로그인해도 화면에 **A 의 사이트 이름이 남았다**(오너 실사용 보고).
 *
 * ■ 왜 그것이 결함인가
 *   ⑴ **거짓말이다.** B 계정은 그 사이트에 접근 권한이 없을 수 있는데 화면은 그것을 고른 것처럼
 *      보여 준다. 눌러야 403 을 만난다.
 *   ⑵ **남의 사이트 이름이 샌다.** B 는 A 가 쓰던 테넌트 코드를 알게 된다.
 *   ⑶ B 가 그 사이트에 **실제로 접근 권한이 있으면** 더 나쁘다 — 자기 사이트인 줄 알고 올린다.
 *
 * ■ 만료는 이 경로가 아니다
 *   여기 있는 것은 **사람이 명시적으로 로그아웃**했을 때 지울 것이다(초기화도 같은 문을 지난다).
 *   토큰 만료는 다른 길로 처리된다 — 만료마다 사이트 선택이 풀리면 쓰던 사람이 매번 다시 고른다.
 */

