/**
 * **사람에게 보이는 알림 글자의 소독.**
 *
 * ■ 왜 필요한가
 *   VS Code 알림 본문은 평문이 아니다. `[글자](스킴:...)` 를 **링크로 렌더**하고, 허용 스킴에
 *   `command:` 와 `file:` 이 들어 있다. 링크를 열 때 명령 실행이 허용돼 있어 명령 아이디에 제한이
 *   없다. 그러면 적대적·탈취된 서버(또는 `apiBase` 가 가리키는 자리에 앉은 쪽)가 내려보낸 한 줄이
 *   **우리 이름으로 뜨는 「누르면 명령이 도는 링크」** 가 된다.
 *
 * ■ 왜 자리마다 부르지 않고 **경계**에 두나
 *   알림을 띄우는 자리가 서른 곳이 넘고, 그중 어디가 서버 글자를 나르는지는 시간이 지나면 갈린다.
 *   "막을 자리를 손으로 열거한다"는 방식은 이 레포에서 이미 한 번 빠뜨려 사고가 났다. 그래서
 *   호출부가 아니라 **알림 함수 한 벌**을 지나게 하고, 그 밖으로 나가는 길이 없는지 기계가 지킨다.
 *
 * ■ 무엇을 하나
 *   ⑴ 제어문자·줄바꿈을 없앤다. ⑵ **링크 문법만** 무력화한다 — 평범한 괄호는 그대로 둔다(우리 문장이
 *   괄호를 쓴다). ⑶ 길이를 자른다.
 */

/**
 * **안쪽 반복의 상한.** 이것을 넘는 링크는 정규식에 **안 잡힌다** — 즉 소독이 새는 자리다.
 * 그래서 [MAX_CAP] 과 한 쌍이다: `MAX_CAP * 4 <= INNER_BOUND` 여야 자른 뒤 길이가 이 상한을
 * 넘을 수 없다. 두 정규식이 이 상수에서 **유도**되므로 둘이 따로 갈릴 수 없다.
 */
const INNER_BOUND = 2048;

/** 자른 뒤 남는 길이의 상한. `INNER_BOUND` 와의 산술이 소독의 전제다 — `notice.test.ts` 가 잰다.  *
 * ⚠ **자르기가 앞에 있어도 천장이 µs 가 아니다.** 자르기가 O(n²) 경로는 닫지만, 남는 최악은
 *   정상 입력의 **5,000~11,000배**다 — 실측: 정상 경로 ~305ns · `"](a:".repeat(512)` 1.6ms ·
 *   `"<a:".repeat(682)` 3.4ms(800KB 입력도 같은 자릿수라 상한이 실제로 듣는다).
 *   **일회성 호출에는 안 느껴지지만 목록·루프에 넣으면 다르다** — N=10,000 이면 30초 정지다.
 *   재현: `node -e '…plainNotice("<a:".repeat(682), 512)…'` 를 2000회 돌려 평균낸다(성능 심의).
*/
export const MAX_CAP = 512;

/** 링크로 렌더될 수 있는 형태. 스킴 목록이 아니라 **콜론이 있는 것 전부**를 본다 — 목록은 늘어난다. */
const LINK_SHAPE = new RegExp(
  `\\]\\s*\\(\\s*([A-Za-z][A-Za-z0-9+.-]*:[^)]{0,${INNER_BOUND}})\\)`,
  "g",
);

/**
 * 각괄호 오토링크(`<command:…>`) — 마크다운의 **두 번째** 링크 문법이다.
 *
 * 이 확장에 `isTrusted` MarkdownString 싱크는 **지금 없다** — 트리 항목은 생 문자열과
 * `ThemeIcon` 객체만 쓴다(`sidebar.ts`). 다만 **툴팁이 더는 전부 리터럴은 아니다**:
 * 작업 폴더 묶음 툴팁이 폴더 경로를 싣는다(그래서 그 자리도 이 소독기를 지난다). 그래도 닫는 이유는 이 소독기가 표방하는 것이
 * 「링크 문법을 무력화한다」이기 때문이다 — 나중에 `isTrusted` MarkdownString 싱크가 하나
 * 생기는 순간, 「소독기를 지났다」는 사실이 거짓 안심이 된다.
 *
 * ⚠ **스킴이 있는 것만 본다.** `<010-1234>`·`a < b` 같은 평범한 글자를 건드리면 우리 문장이 망가진다.
 */
const AUTOLINK_SHAPE = new RegExp(
  `<\\s*([A-Za-z][A-Za-z0-9+.-]*:[^>\\s]{0,${INNER_BOUND}})\\s*>`,
  "g",
);

/**
 * 알림·대화상자에 들어가는 모든 글자가 지난다.
 *
 * ⚠ **자르는 것이 먼저다.** 종전에는 길이 절단이 정규식 **뒤**에 있어서, 300자만 남길 글자라도
 *   전체를 먼저 씹었다. 링크 형태의 안쪽 반복이 닫는 괄호를 못 찾으면 시작 위치마다 끝까지
 *   훑으므로 비용이 길이의 제곱이 된다 — 그리고 이 함수가 받는 글자는 **서버와 아카이브 항목
 *   이름**이다(tar GNU 긴이름 헤더는 상한이 200MB다). 즉 이 소독기가 막으려던 「적대적 서버가
 *   한 줄로 우리 알림을 조종한다」가, 같은 한 줄로 **편집기를 세우는** 길이 됐다.
 *
 *   앞에서 자르면 남는 것이 유계라 그 경로가 닫힌다. 여유를 `cap * 4` 로 두는 이유: 제어문자
 *   제거와 공백 접기가 길이를 줄이므로, 딱 `cap` 만 남기면 잘라도 될 것이 미리 잘려 문장이 짧아진다.
 *
 *   ⚠ **판정이 바뀌는 자리가 하나 있다.** 자르기가 링크 **안쪽**에 떨어지면 닫는 괄호가 사라져
 *     `LINK_SHAPE` 가 안 물고, 결과에 `](스킴:` 이 살아남는다. 마크다운은 닫는 괄호가 없으면
 *     링크로 안 그리므로 실해는 없지만, 이 레포의 시험이 쓰는 오라클(`RENDERS_AS_LINK`)은
 *     「남았다」로 본다 — 「판정은 안 바뀐다」로 적으면 거짓이다.
 *
 * ■ 상한을 `limit` 에서 **유도**한다
 *   `LINK_SHAPE`·`AUTOLINK_SHAPE` 의 안쪽 반복에는 상한이 있고(`{0,2048}`), 그것을 넘는 링크는
 *   **정규식에 안 잡힌다.** 즉 「자르기가 그보다 먼저 온다」가 소독의 전제다. 그 전제를 호출부
 *   규율로만 두면 언젠가 깨진다 — 실제로 이 레포의 시험 하나가 `limit` 을 천만으로 준다.
 *   그래서 `cap` 을 512 로 죈다: `cap * 4 = 2048` 이라 자른 뒤 길이가 안쪽 상한을 **넘을 수 없다.**
 *   상용 최대 호출값이 300 이라 실제 문장은 짧아지지 않는다.
 */
/**
 * 고정점을 찾는 회수의 상한.
 *
 * ⚠ **이 숫자는 안전을 지탱하지 않는다.** 지탱하는 것은 회수를 다 쓰고도 고정점에 못 갔을 때
 *   도는 폴백(문법 글자 제거)이다. 이 값을 1 로 줄여도 결과는 안전하고 **문장만 상한다** —
 *   그러니 「몇 번이면 충분한가」를 여기서 추론하지 않는다. 한 번 돌 때마다 ASCII `)`·`>` 가
 *   반드시 줄어들어 종료는 보장된다.
 */
const DEFANG_PASSES = 4;

/**
 * 링크 문법이 **더 안 나올 때까지** 무력화한다.
 *
 * ⚠ **한 번만 돌리면 샌다** — 추론이 아니라 실측이다. 겹친 링크 하나가 한 패스를 통과해
 *   **렌더되는 링크 모양 그대로** 남는다. 남은 것의 목적지에는 전각 괄호가 한 글자 섞여 있어
 *   오늘의 VS Code 는 그것을 실행 가능한 명령으로 풀지 못하지만, 「한 글자 차이로 안 도는 링크」는
 *   막았다고 할 수 있는 상태가 아니다. 목적지 끝의 문장부호를 다듬는 렌더러가 하나 끼는 순간
 *   그대로 살아난다.
 *
 *   이 소독기가 표방하는 것은 「링크 문법을 무력화한다」다. 그러면 **더 나올 것이 없을 때까지**
 *   돌아야 그 말이 참이 된다. 입력은 이미 유계(`cap * 4`)라 회수도 유계다.
 *
 * 상한 안에 고정점에 못 가면 **문법 글자 자체를 지운다.** 「아마 안전할 것」으로 넘기지 않는다 —
 * 문장이 상해도 누르면 명령이 도는 링크보다 낫다.
 */
function defang(text: string): string {
  let out = text;
  for (let pass = 0; pass < DEFANG_PASSES; pass += 1) {
    const next = out
      .replace(LINK_SHAPE, (_m, inner: string) => `\uFF3D\uFF08${inner}\uFF09`)
      .replace(AUTOLINK_SHAPE, (_m, inner: string) => `\uFF1C${inner}\uFF1E`);
    if (next === out) return out;
    out = next;
  }
  return out.replace(/[\]()<>]/g, " ");
}

export function plainNotice(text: unknown, limit = 300): string {
  if (typeof text !== "string") return "";
  const cap = Math.min(limit, MAX_CAP);
  const head = text.length > cap * 4 ? text.slice(0, cap * 4) : text;
  // ⚠ **강한 재정렬·격리도 지운다.** 종전에는 약한 방향표(U+200E/200F)만 지우고
  //    **U+202A~202E(강한 재정렬)·U+2066~2069(격리)** 를 남겼다 — 같은 Cf 부류인데 갈랐다.
  //    이 함수가 스스로 「제어문자를 없앤다」고 적어 둔 계약과 어긋났고, **남이 이름 짓는 로컬
  //    경로**가 표시 표면에 오르면서(작업 폴더 묶음·발행 확인 모달) 그 구멍이 실질화됐다:
  //    폴더 이름 하나로 확인 문면의 지시대상을 **시각적으로 뒤집을 수** 있다(보안 심의).
  const stripped = head.replace(
    /[\u0000-\u001f\u007f-\u009f\u200b-\u200f\u202a-\u202e\u2066-\u2069\u2028\u2029]+/g,
    " ",
  );
  const tidy = defang(stripped).replace(/\s+/g, " ").trim();
  return tidy.length > cap ? `${tidy.slice(0, cap)}\u2026` : tidy;
}

/**
 * **숫자로 보여 줄 값.** 서버가 준 `number` 를 문장에 넣을 때 쓴다.
 *
 * ⚠ 타입이 `number` 라고 런타임에도 숫자인 것은 아니다. `api.ts` 는 응답 본문의 필드 타입을
 *   검증하지 않으므로, 적대적·탈취된 서버가 `revisionNo` 에 `1 [열기](command:…)` 를 넣으면
 *   그 문자열이 그대로 알림에 실린다 — `notice.ts` 가 상정한 바로 그 위협 모델이다.
 *   `ours(...)` 는 값을 바꾸지 않는 **표기**라 이것을 막지 못한다(심의 실증).
 *
 * 숫자로 읽히면 숫자를, 아니면 `?` 를 돌려준다. **모르면 보여 주지 않는 쪽**이다.
 */
export const count = (value: unknown): string => {
  // ⚠ **`Number(...)` 에 바로 넘기지 않는다.** `Number(null)`·`Number("")`·`Number([])`·
  //    `Number(false)` 는 **전부 0** 이다. 서버가 `revisionNo` 를 null 로 보내면 화면에
  //    「버전 0」이 뜬다 — 모르는 것을 아는 척하는 자리이고, 이 함수가 배격한 바로 그것이다.
  //    문자열도 받지 않는다: `"5"` 를 5 로 읽어 주면 `"1 [열기](command:…)"` 만 걸러지고
  //    **서버가 숫자 자리에 뭘 넣었는지**는 계속 안 보인다.
  if (typeof value !== "number" && typeof value !== "bigint") return "?";
  const n = Number(value);
  return Number.isFinite(n) ? String(n) : "?";
};

/**
 * 숫자 뒤에 붙일 조사. **이름만 받고, 글자는 이 파일이 낸다.**
 *
 * ⚠ **부르는 쪽에서 리터럴 두 개를 받지 않는다.** 그러면 그 두 글자가 소독을 안 지나고 문장에
 *   그대로 이어 붙는다 — 유니온이 생 `string` 을 막지만 캐스트 한 줄이면 뚫리고, 알림 소독
 *   검사기는 소독기의 **인자를 보지 않으므로** 초록인 채로 나간다(변이로 실측: 알림에 클릭
 *   링크가 살았다). 키만 받고 표에서 꺼내면 그 갈래가 구조적으로 사라진다.
 */
export type Josa = "이/가" | "을/를" | "은/는" | "으로/로";

const JOSA_PAIRS: Record<Josa, readonly [string, string]> = {
    "이/가": ["이", "가"],
    "을/를": ["을", "를"],
    "은/는": ["은", "는"],
    "으로/로": ["으로", "로"],
};

/**
 * **숫자 + 조사.** `버전 ${count(n)} 가` 는 1·3·6·7·8·10 에서 전부 틀린다 — 조사는 숫자를 **읽는
 * 소리**의 받침이 정하기 때문이다(1=일·10=십 은 받침이 있고 2=이·5=오 는 없다).
 *
 * ⚠ **「으로/로」은 규칙이 다르다.** ㄹ 받침 뒤에는 「으로」가 아니라 「로」다(1=일 → "1로",
 *   7=칠 → "7로"). 다른 조사에서 ㄹ 은 받침으로 치므로("1이"·"1은"·"1을"), 받침을 있다/없다
 *   둘로만 나누면 이 자리가 반드시 틀린다. 그래서 세 갈래로 나눈다: 없음 · ㄹ · 그 밖.
 *
 * 판정은 [count] 가 **실제로 그린 문자열의 끝 글자**로 한다. 값을 다시 해석하지 않으므로 화면에
 * 뜬 글자와 조사가 어긋날 수 없고, 숫자가 아닌 값이 와서 [count] 가 `?` 를 돌려준 자리에도
 * 조사는 붙어야 하므로 받침 없는 쪽으로 접는다.
 *
 * 끝자리 0 은 언제나 받침이다 — 마지막으로 읽는 소리가 십·백·천·만(0 자체는 영)이기 때문이다.
 *
 * ⚠ **던지지 않는다.** 표에 없는 이름이 오면 조사 없이 숫자만 돌려준다. 소독기 한 벌 중 하나만
 *   예외를 내면 알림 경로에 새 실패 모드가 생긴다 — `plainNotice`·`count` 는 어떤 입력에도
 *   안 던진다.
 *
 * ⚠ **[count] 를 감싼다** — 소독 보장을 물려받는다. 돌려주는 것은 `count` 의 출력과 [JOSA_PAIRS]
 *   의 글자뿐이고 **둘 다 이 파일의 것**이라, 서버 문자열이 실릴 자리가 없다.
 */
export const countJosa = (value: unknown, josa: Josa): string => {
    const drawn = count(value);
    const pair = JOSA_PAIRS[josa];
    if (!pair) return drawn;
    const last = drawn.slice(-1);
    // 없음 = 2·4·5·9(이·사·오·구) · ㄹ = 1·7·8(일·칠·팔) · 그 밖 = 0·3·6(영/십·삼·육)
    const kind = /[2459]/.test(last) ? "none" : /[178]/.test(last) ? "rieul" : /[036]/.test(last) ? "other" : "none";
    const withoutFinal = kind === "none" || (kind === "rieul" && josa === "으로/로");
    return `${drawn}${withoutFinal ? pair[1] : pair[0]}`;
};

/**
 * **서버가 정하지 않은 값**이라는 표기. 소독하지 않고 알림에 넣어도 되는 것에만 붙인다.
 *
 * 값을 바꾸지 않는다 — 오직 **사람이 한 번 판단했다는 사실**을 코드에 남긴다. `check-notice.mjs`
 * 는 알림에 닿는 모든 보간을 **기본 거부**하고, 소독기 호출과 이 표기만 통과시킨다.
 *
 * ⚠ 첫 판 검사기는 반대였다 — 위험한 **이름 목록**(`tenant`·`presetName`)을 열거해 막았다.
 *   그러면 같은 서버값이 **다른 이름**에 담기는 순간 소독도 검사도 안 된다(재심의 실증: `code`·
 *   `current`·`expected`·`uploaded`·`errorCode` 다섯 자리가 그렇게 샜다). `notice.ts` 가 배격한
 *   "막을 자리를 손으로 열거한다"를 식별자 층위에서 되풀이한 것이다. 목록을 뒤집는다 —
 *   **허용을 열거하고 나머지를 거부한다.**
 *
 * 붙이기 전에 물을 것: 이 값이 서버 응답에서 **한 번이라도** 유래하는가? 그렇다면 문자열은
 * `plainNotice`, 숫자는 [count] 다 — 타입이 `number` 라는 것은 런타임 보장이 아니다.
 */
export const ours = <T>(value: T): T => value;
