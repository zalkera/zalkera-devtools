/**
 * **사람에게 보이는 알림 글자의 소독.**
 *
 * ■ 왜 필요한가
 *   VS Code 알림 본문은 평문이 아니다. `[글자](스킴:...)` 를 **링크로 렌더**하고, 허용 스킴에
 *   `command:` 와 `file:` 이 들어 있다. 링크를 열 때 명령 실행이 허용돼 있어 명령 아이디에 제한이
 *   없다. 그러면 적대적·탈취된 서버(또는 `apiBase` 가 가리키는 자리에 앉은 쪽)가 내려보낸 한 줄이
 *   **우리 이름으로 뜨는 「누르면 명령이 도는 링크」** 가 된다.
 *
 * ■ 왜 자리마다 부르지 않고 **경계**에 두나
 *   알림을 띄우는 자리가 서른 곳이 넘고, 그중 어디가 서버 글자를 나르는지는 시간이 지나면 갈린다.
 *   "막을 자리를 손으로 열거한다"는 방식은 이 레포에서 이미 한 번 빠뜨려 사고가 났다. 그래서
 *   호출부가 아니라 **알림 함수 한 벌**을 지나게 하고, 그 밖으로 나가는 길이 없는지 기계가 지킨다.
 *
 * ■ 무엇을 하나
 *   ⑴ 제어문자·줄바꿈을 없앤다. ⑵ **링크 문법만** 무력화한다 — 평범한 괄호는 그대로 둔다(우리 문장이
 *   괄호를 쓴다). ⑶ 길이를 자른다.
 */

/** 링크로 렌더될 수 있는 형태. 스킴 목록이 아니라 **콜론이 있는 것 전부**를 본다 — 목록은 늘어난다. */
const LINK_SHAPE = /\]\s*\(\s*([A-Za-z][A-Za-z0-9+.-]*:[^)]*)\)/g;

/** 알림·대화상자에 들어가는 모든 글자가 지난다. */
export function plainNotice(text: unknown, limit = 300): string {
    if (typeof text !== "string") return "";
    const stripped = text.replace(/[\u0000-\u001f\u007f-\u009f\u200b-\u200f\u2028\u2029]+/g, " ");
    // `](스킴:...)` 만 전각으로 바꾼다. 링크가 아니게 되고 글자는 남는다.
    const defanged = stripped.replace(LINK_SHAPE, (_m, inner: string) => `\uFF3D\uFF08${inner}\uFF09`);
    const tidy = defanged.replace(/\s+/g, " ").trim();
    return tidy.length > limit ? `${tidy.slice(0, limit)}\u2026` : tidy;
}
