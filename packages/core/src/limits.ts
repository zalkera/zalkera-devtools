/**
 * **크기 상한 — 한 곳에서 유도한다.**
 *
 * ■ 왜 모으나
 *   같은 성질의 상한이 네 파일에 **리터럴로 복사**돼 있었고, 교차 import 는 0건이었다. 그중 하나가
 *   실제로 모순으로 발화했다: `fetchSource` 가 400MB 를 넘기는데 `untar` 가 `Math.min(…, 200MB)` 로
 *   되죄어, **호출부가 건 상한이 무효**였다. 주석은 「넘기니까 400MB 가 선다」고 적고 코드는 200MB 를
 *   세웠다. 게다가 같은 파서의 스트리밍 경로는 넘긴 값을 그대로 써서, **경로에 따라 상한이 갈렸다** —
 *   `untar.ts` 스스로 「호출부가 건 상한이 경로에 따라 있다 없다 하면 그건 상한이 아니다」라고 적어 둔
 *   바로 그 형상이다.
 *
 * ■ 유도의 사슬
 *   상류는 **전선에서 받아들이는 바이트**([MAX_DOWNLOAD_BYTES]) 하나다. 해제 산출물 상한은 거기에
 *   실측 팽창비를 곱해 **계산한다** — 적어 두는 것이 아니라. 다운로드 상한을 바꾸면 해제 상한이
 *   따라 움직인다.
 *
 * ■ 형식이 다르다고 갈리지 않는다
 *   zip 과 tar.gz 는 같은 소스를 나르는 두 포장일 뿐이다. 두 형식이 다른 상한을 쓰면, 같은 사이트가
 *   포장에 따라 받아지거나 거부된다.
 */

/**
 * 전선에서 받아들이는 최대 바이트. **모든 크기 상한의 상류**다.
 *
 * 업로드 상한(100MB · `publish.ts`)에 여유를 얹은 값이다 — 우리가 받아 준 것은 되돌려줄 수 있어야
 * 한다. 올릴 수는 있는데 되받을 수 없으면 그것이 곧 데이터 유폐다.
 */
export const MAX_DOWNLOAD_BYTES = 150 * 1024 * 1024;

/**
 * **사이트 소스**의 실측 팽창비 — 압축본 대비 해제 산출물의 배수.
 *
 * ⚠ **이 값은 소스 코퍼스의 것이다.** 프리셋 2종 실측이 2.5~3배였다. 의존성 페이로드는 **다른
 *   코퍼스**이고 실측이 3.71배(158→586MB)·3.59배(167→600MB)다 — `payload.ts` 가 자기
 *   `EXTRACT_RATIO_CAP`(8) 을 따로 갖는 이유이고, 두 값을 하나로 뭉개면 안 된다. 한 번 뭉갰다가
 *   페이로드 해제가 통째로 막혔다(마감 심의 차단).
 */
export const SOURCE_EXPANSION = 3;

/**
 * **사이트 소스** 해제 산출물의 총량 상한. 유도값이다 — 전선 상한 x 소스 팽창비.
 *
 * 무제한 해제는 확장 호스트를 OOM 으로 죽이고, 그러면 **다른 확장까지 함께 죽는다.**
 *
 * 이것은 「모든 해제의 천장」이 아니라 **소스 경로의 기본값**이다. 한때 이 값으로 모든 호출부를
 * 되죘는데, 자기 입력 크기에서 상한을 유도하던 의존성 페이로드 경로가 통째로 막혔다(요구
 * 1264MB · 실제 산출물 586MB → 450MB 로 깎임). 그 고장은 조용했다 — `tryFetchPayload` 가
 * `null` 로 수렴해 「미리 구운 의존성 가속기가 영영 안 켜지는」 모습으로만 나타난다.
 * 호출부는 **자기 입력에서 자기 상한을 유도한다** — 그것이 이 레포의 실제 계약이다.
 */
export const MAX_EXTRACT_BYTES = MAX_DOWNLOAD_BYTES * SOURCE_EXPANSION;

/**
 * 항목 **하나**의 상한. 총량([MAX_EXTRACT_BYTES])과 목적이 다르다 — 큰 것은 트리 **전체**이지
 * 한 파일이 아니라는 관찰에서 나온 휴리스틱이다(의존성 트리의 개별 파일은 수 MB 를 안 넘는다).
 *
 * ⚠ **유도값이 아니라 판단값이다.** 그래서 더더욱 한 곳에 둔다 — 종전에는 zip 200MB · tar 256MB 로
 *   갈려 있었고, 양쪽 주석이 나란히 「두 형식이 다른 기준을 쓸 이유가 없다」고 적고 있었다.
 *   둘 중 **좁은 쪽**을 쓴다: 넓히면 종전에 막히던 것이 통과하는데, 그 변화를 정당화할 근거가 없다.
 *
 * 2GB 를 넘는 신고는 네이티브 abort 를 부르므로(재심의 차단) 어느 값이든 그보다 훨씬 아래여야 한다.
 */
export const MAX_ENTRY_BYTES = 200 * 1024 * 1024;
